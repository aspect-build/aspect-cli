/// Undocumented, and defined in this repo rather than a module (`@mod//…`) —
/// a module's task is not the reader's to fix.
fn needs_summary_warning(summary: &str, defined_in: &str) -> bool {
    summary.is_empty() && !defined_in.starts_with('@')
}

fn defined_in_label(path: &Path, aspect_root: &Path, modules: &[Mod]) -> String {
    for r#mod in modules {
        if r#mod.is_root() || !path.starts_with(&r#mod.root) {
            continue;
        }
        let rel = path.strip_prefix(&r#mod.root).unwrap_or(path);
        return format!("@{}//{}", r#mod.name, rel.display());
    }
    let rel = path.strip_prefix(aspect_root).unwrap_or(path);
    format!("{}", rel.display())
}

fn deepest_subcommand(matches: &ArgMatches) -> Option<&ArgMatches> {
    let (_, mut leaf) = matches.subcommand()?;
    while let Some((_, next)) = leaf.subcommand() {
        leaf = next;
    }
    Some(leaf)
}

/// The deepest selected subcommand's name — the task kind (`build`, `test`, …),
/// used as the default task name when neither `--task:name` nor `--task-key`
/// is given.
fn leaf_command_name(matches: &ArgMatches) -> Option<String> {
    let (mut name, mut leaf) = matches.subcommand()?;
    while let Some((next_name, next)) = leaf.subcommand() {
        name = next_name;
        leaf = next;
    }
    Some(name.to_owned())
}

fn parse_task_name(s: &str) -> Result<String, String> {
    if s.chars()
        .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-')
    {
        Ok(s.to_owned())
    } else {
        Err(format!(
            "'{}' contains invalid characters (allowed: A-Za-z0-9, _, -)",
            s
        ))
    }
}

/// A friendly random suffix (e.g. "fluffy-parakeet") appended to the task kind
/// to form a default `--task:name`. Falls back to a short UUID fragment.
fn generate_name_suffix() -> String {
    names::Generator::with_naming(names::Name::Plain)
        .next()
        .unwrap_or_else(|| uuid::Uuid::new_v4().to_string()[..8].to_string())
}

fn parse_task_uuid(s: &str) -> Result<String, String> {
    uuid::Uuid::parse_str(s)
        .map(|u| u.to_string())
        .map_err(|_| {
            format!(
                "'{}' is not a valid UUID (expected xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx)",
                s
            )
        })
}

fn parse_timing_mode(s: &str) -> Result<TimingMode, String> {
    s.parse::<TimingMode>()
}

fn help_text(description: &Option<String>) -> Resettable<StyledStr> {
    match description {
        Some(text) => Resettable::Value(text.into()),
        None => Resettable::Reset,
    }
}

fn short_char(short: &Option<String>) -> Resettable<char> {
    match short {
        Some(text) => Resettable::Value(text.chars().next().unwrap().into()),
        None => Resettable::Reset,
    }
}

