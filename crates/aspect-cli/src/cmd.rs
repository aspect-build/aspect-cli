const TASK_ID_KEY: &str = "@@@$'__AXL_TASK_ID__'$@@@";
/// `aspect feature [<name>]`: routed to the feature-help renderer in `main`.
const FEATURE_COMMAND: &str = "feature";
/// `aspect describe`: routed to the machine-readable surface dump in `main`.
const DESCRIBE_COMMAND: &str = "describe";
/// Top-level command names `main` intercepts before task parsing; a top-level
/// task of any of these kinds would be unreachable, so it is rejected at build
/// time (see `Tree::insert`). Reachable when nested under a group.
const RESERVED_TOP_LEVEL_COMMANDS: &[&str] = &[
    FEATURE_COMMAND,
    DESCRIBE_COMMAND,
    crate::credential_helper::GET_COMMAND,
];
const TASK_COMMAND_DISPLAY_ORDER: usize = 0;
const TASK_GROUP_DISPLAY_ORDER: usize = 1;

#[derive(Error, Debug)]
pub enum CmdError {
    #[error("task {0:?} (defined in {1:?}) cannot have more than {2} group levels")]
    TooManyGroups(String, String, usize),
    #[error("task {0:?} in group {1:?} (defined in {2:?}) conflicts with another task or group")]
    NameConflict(String, Vec<String>, String),
    #[error(
        "task {0:?} (defined in {1:?}) uses the reserved command name {2:?}; \
         rename it or nest it under a group"
    )]
    ReservedName(String, String, String),
    #[error("no task selected")]
    NoTaskSelected,
}

/// Bridge from runtime values (tasks, features, modules) to a parsed Clap surface.
pub struct Cmd<'a, 'v> {
    pub tasks: Vec<&'v dyn TaskLike<'v>>,
    pub features: Vec<&'v dyn FeatureLike<'v>>,
    pub aspect_root: &'a Path,
    pub modules: &'a [Mod],
}

/// Carries the parsed CLI state needed to execute the selected task and its features.
pub struct Dispatch {
    pub task_id: usize,
    pub task_name: String,
    /// Whether `task_name` carries real meaning — explicitly set (`--task:name`
    /// / `--task-key`) or CI-job-derived — vs a local autogenerated placeholder.
    /// Drives whether the task header surfaces the name alongside the kind.
    pub task_name_meaningful: bool,
    pub task_friendly_name: Option<String>,
    pub task_uuid: Option<String>,
    pub timing: TimingMode,
    matches: ArgMatches,
}

impl<'a, 'v> Cmd<'a, 'v> {
    /// Build the full root Clap command (`aspect`) with all task subcommands.
    pub fn build(&self, version: &str) -> Result<Command, CmdError> {
        let feature_blocks: Vec<FeatureBlock> = self
            .features
            .iter()
            .filter_map(|f| feature_block(*f))
            .collect();

        let cli_header = banner::line(version);

        let mut tree = Tree::default();
        for (idx, task) in self.tasks.iter().enumerate() {
            let label = defined_in_label(task.path(), self.aspect_root, self.modules);
            let task_cmd = task_command(idx, *task, &label, &feature_blocks, &cli_header);
            tree.insert(*task, &label, task_cmd)?;
        }

        let group_section = group_section(&tree.group_rows());
        let root = Command::new("aspect")
            .bin_name("aspect")
            .about("Aspect's programmable task runner built on top of Bazel\n{ Correct, Fast, Usable } -- Choose three")
            .subcommand_value_name("TASK|GROUP|COMMAND")
            .disable_help_subcommand(true)
            // Display only; `version` stays the bare number for AXL and telemetry.
            .version(cargo_pkg_display_version())
            .disable_version_flag(true)
            .arg(
                ClapArg::new("version")
                    .short('v')
                    .long("version")
                    .action(ArgAction::Version)
                    .help("Print version"),
            )
            .arg(
                ClapArg::new("task:name")
                    .long("task:name")
                    .value_name("NAME")
                    .global(true)
                    .value_parser(parse_task_name)
                    .help("A short name uniquely identifying this task invocation. Allowed characters: A-Za-z0-9, _, -. Useful when the same task runs multiple times in one pipeline (e.g. 'backend', 'frontend'). Defaults to '<kind>-<suffix>' if not set."),
            )
            .arg(
                ClapArg::new("task:friendly-name")
                    .long("task:friendly-name")
                    .value_name("FRIENDLY_NAME")
                    .global(true)
                    .help("A human-readable label for this task invocation, shown on status surfaces. Defaults to --task:name."),
            )
            .arg(
                ClapArg::new("task-key")
                    .long("task-key")
                    .value_name("KEY")
                    .global(true)
                    .hide(true)
                    .value_parser(parse_task_name)
                    .help("Deprecated alias for --task:name; will be removed in a future release."),
            )
            .arg(
                ClapArg::new("task:id")
                    .long("task:id")
                    .value_name("UUID")
                    .global(true)
                    .value_parser(parse_task_uuid)
                    .help("A UUID uniquely identifying this task invocation. Auto-generated if not set."),
            )
            .arg(
                ClapArg::new("task:timing-summary")
                    .long("task:timing-summary")
                    .value_name("LEVEL")
                    .global(true)
                    .value_parser(parse_timing_mode)
                    .default_value("detailed")
                    .help("Verbosity of the phase-timing breakdown trailing the task completion line: 'none' (no timing summary), 'total' (total only), 'short' (inline phases), or 'detailed' (multi-line with descriptions; default)."),
            )
            .subcommand(
                // `feature` is not a task: its parsing exists only so `main`
                // can route to `Cmd::print_feature_help`. Disable clap's auto
                // help flag (otherwise `feature --help` renders clap's own
                // help, leaking the global `--task:*` args) and accept a no-op
                // `-h`/`--help` so it falls through to our renderer instead.
                Command::new("feature")
                    .about("List features and show a feature's flags")
                    .hide(true)
                    .disable_help_flag(true)
                    .arg(
                        ClapArg::new("name")
                            .value_name("NAME")
                            .required(false),
                    )
                    .arg(
                        ClapArg::new("help")
                            .short('h')
                            .long("help")
                            .action(ArgAction::SetTrue)
                            .hide(true),
                    ),
            )
            .subcommand(
                // `describe` is not a task: parsing exists only so `main` can
                // route to `Cmd::print_describe`. The whole point is that a
                // reader with no prior knowledge of this repo can enumerate the
                // surface in one call, so it defaults to JSON rather than
                // requiring the flag to be known up front.
                Command::new(DESCRIBE_COMMAND)
                    .about("Print the resolved task, flag and feature surface as JSON")
                    .hide(true)
                    .arg(
                        ClapArg::new("task")
                            .value_name("TASK")
                            .required(false)
                            .help("Describe one task in full, e.g. `aspect describe 'cache diff'`. Omit for the index."),
                    )
                    .arg(
                        ClapArg::new("output")
                            .long("output")
                            .short('o')
                            .value_name("FORMAT")
                            .default_value("json")
                            .value_parser(PossibleValuesParser::new(["json"]))
                            .help("Output format."),
                    ),
            )
            .subcommand(Command::new("version").about("Print version").hide(true))
            .subcommand(
                Command::new("help")
                    .about("Print this message or the help of the given subcommand(s)")
                    .hide(true),
            )
            .help_template(format!(
                "{cli_header}\n\n{{about-with-newline}}\n{{usage-heading}} {{usage}}\n\n\x1b[1;4mTasks:\x1b[0m\n{{subcommands}}{group_section}\n\x1b[1;4mCommands:\x1b[0m\n  \x1b[1mdescribe\x1b[0m  Print the resolved task, flag and feature surface as JSON\n  \x1b[1mfeature\x1b[0m   List features and their flags\n  \x1b[1mversion\x1b[0m   Print version\n  \x1b[1mhelp\x1b[0m      Print this message or the help of the given subcommand(s)\n\n\x1b[1;4mOptions:\x1b[0m\n{{options}}"
            ));

        tree.attach(root, version)
    }

    /// Walk the parsed matches to the deepest subcommand and extract task ids + uuids.
    pub fn dispatch(&self, matches: ArgMatches) -> Result<Dispatch, CmdError> {
        let leaf = deepest_subcommand(&matches).ok_or(CmdError::NoTaskSelected)?;
        let task_id = *leaf
            .get_one::<usize>(TASK_ID_KEY)
            .ok_or(CmdError::NoTaskSelected)?;
        // Resolution order: --task:name wins; the deprecated --task-key is
        // accepted as an alias and always warns; otherwise the name defaults
        // to the task kind (the deepest selected subcommand name).
        let explicit_name = leaf
            .get_one::<String>("task:name")
            .filter(|s| !s.is_empty())
            .cloned();
        let deprecated_key = leaf
            .get_one::<String>("task-key")
            .filter(|s| !s.is_empty())
            .cloned();
        if deprecated_key.is_some() {
            diag::warn(
                "--task-key is deprecated; use --task:name instead. \
                 --task-key will be removed in a future release.",
            );
        }
        // An explicit name (`--task:name` / `--task-key`) is meaningful as-is.
        // Otherwise auto-generate: `<kind>-<ci-job>` on CI (de-duped per
        // run/machine, meaningful), else `<kind>-<random-suffix>` (a local
        // placeholder, not meaningful).
        let (task_name, task_name_meaningful) = match explicit_name.or(deprecated_key) {
            Some(name) => (name, true),
            None => {
                let kind = leaf_command_name(&matches).unwrap_or_default();
                let auto = axl_runtime::ci::auto_task_name(&kind, generate_name_suffix);
                (auto.name, auto.meaningful)
            }
        };
        let task_friendly_name = leaf.get_one::<String>("task:friendly-name").cloned();
        let task_uuid = leaf.get_one::<String>("task:id").cloned();
        let timing = leaf
            .get_one::<TimingMode>("task:timing-summary")
            .copied()
            .unwrap_or_default();
        Ok(Dispatch {
            task_id,
            task_name,
            task_name_meaningful,
            task_friendly_name,
            task_uuid,
            timing,
            matches,
        })
    }

    /// Render `aspect feature [<name>]` and return the process exit code.
    ///
    /// With no name, lists every active feature (keyed by the kebab slug the
    /// user passes back in). With a name, prints just that feature's flags. An
    /// unknown name lists the valid ones on stderr and exits 2.
    /// Print the resolved surface as JSON (`aspect describe`).
    ///
    /// Pretty-printed rather than compact: the output is read far more often
    /// than it is piped into another program, and diffs of it are useful.
    pub fn print_describe(&self, version: &str, task: Option<&str>) -> ExitCode {
        let doc = match task {
            None => describe_index(version, &self.tasks, &self.features),
            Some(name) => {
                let full = describe_json(
                    version,
                    &self.tasks,
                    &self.features,
                    self.aspect_root,
                    self.modules,
                );
                match select_task(&full, name) {
                    Some(t) => t,
                    None => {
                        eprintln!(
                            "error: no task {name:?}. Run `aspect describe` for the list of commands."
                        );
                        return ExitCode::FAILURE;
                    }
                }
            }
        };
        match serde_json::to_string_pretty(&doc) {
            Ok(s) => {
                println!("{s}");
                ExitCode::SUCCESS
            }
            Err(e) => {
                eprintln!("error: failed to serialize the CLI surface: {e}");
                ExitCode::FAILURE
            }
        }
    }

    pub fn print_feature_help(&self, version: &str, name: Option<&str>) -> ExitCode {
        let mut blocks: Vec<(&dyn FeatureLike<'_>, FeatureBlock)> = self
            .features
            .iter()
            .filter_map(|f| feature_block(*f).map(|b| (*f, b)))
            .collect();
        blocks.sort_by(|(a, _), (b, _)| a.name().cmp(&b.name()));

        match name {
            None => {
                print!(
                    "{}",
                    render_feature_list(version, &blocks, color::stdout_supports_color())
                );
                ExitCode::SUCCESS
            }
            Some(name) => match blocks.iter().find(|(f, _)| f.name() == name) {
                Some((feat, block)) => {
                    render_feature_detail(version, *feat, block, self.aspect_root, self.modules)
                        .print_help()
                        .ok();
                    ExitCode::SUCCESS
                }
                None => {
                    let valid: Vec<String> = blocks.iter().map(|(f, _)| f.name()).collect();
                    eprintln!(
                        "\x1b[1;31merror:\x1b[0m unknown feature {name:?}. Valid features: {}",
                        valid.join(", ")
                    );
                    ExitCode::from(2)
                }
            },
        }
    }
}

impl Dispatch {
    /// Build the merged `Arguments` for the selected task.
    pub fn task_args<'v>(&self, task: &dyn TaskLike<'v>, heap: Heap<'v>) -> Arguments<'v> {
        let leaf = deepest_subcommand(&self.matches).expect("dispatch built from valid matches");
        merge_args(task.args(), task.overrides(), leaf, heap, Scope::Task)
    }

    /// Build the merged `Arguments` for a feature implementation invocation.
    pub fn feature_args<'v>(&self, feat: &dyn FeatureLike<'v>, heap: Heap<'v>) -> Arguments<'v> {
        let leaf = deepest_subcommand(&self.matches).expect("dispatch built from valid matches");
        let prefix = feat.name();
        merge_args(
            feat.args(),
            feat.overrides(),
            leaf,
            heap,
            Scope::Feature(&prefix),
        )
    }
}

// ── Scope: how an arg's Clap key is derived ────────────────────────────────

#[derive(Copy, Clone)]
enum Scope<'a> {
    Task,
    Feature(&'a str),
}

fn clap_id(scope: Scope<'_>, name: &str, arg: &Arg) -> String {
    match scope {
        Scope::Task => name.to_owned(),
        // Always prefixed, even under a `long` override: task arg IDs are bare
        // names, so a prefixed feature ID can never collide with one — only the
        // *long flag* can, and `task_command` resolves that by skipping the
        // feature arg on tasks whose own args already claim the flag.
        Scope::Feature(prefix) => {
            let long = arg
                .long_override()
                .map(str::to_owned)
                .unwrap_or_else(|| name.replace('_', "-"));
            if prefix.is_empty() {
                long
            } else {
                format!("{}:{}", prefix, long)
            }
        }
    }
}

fn long_flag(scope: Scope<'_>, name: &str, arg: &Arg) -> String {
    if let Some(lo) = arg.long_override() {
        return lo.to_owned();
    }
    match scope {
        Scope::Task => name.replace('_', "-"),
        Scope::Feature(prefix) => {
            let long = name.replace('_', "-");
            if prefix.is_empty() {
                long
            } else {
                format!("{}:{}", prefix, long)
            }
        }
    }
}

// ── Arg → ClapArg ──────────────────────────────────────────────────────────

fn arg_to_clap(scope: Scope<'_>, name: &str, arg: &Arg) -> ClapArg {
    let id = clap_id(scope, name, arg);
    let long = long_flag(scope, name, arg);
    match arg {
        Arg::String {
            required,
            default,
            short,
            values,
            description,
            bare,
            ..
        } => {
            let mut it = ClapArg::new(id.clone())
                .long(long.clone())
                .value_name(long)
                .short(short_char(short))
                .help(help_text(description))
                .required(*required)
                .default_value(default.clone());
            it = if let Some(values) = values {
                it.value_parser(PossibleValuesParser::new(values))
            } else {
                it.value_parser(value_parser!(String))
            };
            // `bare = "…"` makes a valueless `--flag` legal. `require_equals` keeps
            // the next argv token from being swallowed as the value, so
            // `--remote //foo` parses as bare flag + target rather than
            // `--remote=//foo` (same shape as the Boolean arm below).
            if let Some(bare) = bare {
                it = it
                    .num_args(0..=1)
                    .require_equals(true)
                    .default_missing_value(bare.clone());
            }
            it
        }
        Arg::Boolean {
            required,
            default,
            short,
            description,
            ..
        } => ClapArg::new(id)
            .long(long.clone())
            .value_name(long)
            .short(short_char(short))
            .help(help_text(description))
            .required(*required)
            .default_value(if *default { "true" } else { "false" })
            .value_parser(value_parser!(bool))
            .num_args(0..=1)
            .require_equals(true)
            .default_missing_value("true"),
        Arg::Int {
            required,
            default,
            short,
            description,
            ..
        } => ClapArg::new(id)
            .long(long.clone())
            .value_name(long)
            .short(short_char(short))
            .help(help_text(description))
            .required(*required)
            .default_value(default.to_string())
            .value_parser(value_parser!(i32)),
        Arg::UInt {
            required,
            default,
            short,
            description,
            ..
        } => ClapArg::new(id)
            .long(long.clone())
            .value_name(long)
            .short(short_char(short))
            .help(help_text(description))
            .required(*required)
            .default_value(default.to_string())
            .value_parser(value_parser!(u32)),
        Arg::Positional {
            minimum,
            maximum,
            default,
            description,
        } => {
            let mut it = ClapArg::new(id.clone())
                .value_parser(value_parser!(String))
                .value_name(id)
                .help(help_text(description))
                .num_args(*minimum as usize..=*maximum as usize);
            if let Some(default) = default {
                it = it.default_values(default);
            }
            it
        }
        Arg::TrailingVarArgs { description } => ClapArg::new(id.clone())
            .value_parser(value_parser!(String))
            .value_name(id)
            .help(help_text(description))
            .allow_hyphen_values(true)
            .last(true)
            .num_args(0..),
        Arg::StringList {
            required,
            default,
            short,
            description,
            ..
        } => {
            let mut it = ClapArg::new(id)
                .long(long.clone())
                .value_name(long)
                .short(short_char(short))
                .help(help_text(description))
                .action(ArgAction::Append)
                .required(*required)
                .value_parser(value_parser!(String));
            if !default.is_empty() {
                it = it.default_values(default.iter().cloned());
            }
            it
        }
        Arg::BooleanList {
            required,
            default,
            short,
            description,
            ..
        } => {
            let mut it = ClapArg::new(id)
                .long(long.clone())
                .value_name(long)
                .short(short_char(short))
                .help(help_text(description))
                .action(ArgAction::Append)
                .required(*required)
                .value_parser(value_parser!(bool))
                .num_args(0..=1)
                .default_missing_value("true");
            if !default.is_empty() {
                it = it.default_values(default.iter().map(|&b| if b { "true" } else { "false" }));
            }
            it
        }
        Arg::IntList {
            required,
            default,
            short,
            description,
            ..
        } => {
            let mut it = ClapArg::new(id)
                .long(long.clone())
                .value_name(long)
                .short(short_char(short))
                .help(help_text(description))
                .action(ArgAction::Append)
                .required(*required)
                .value_parser(value_parser!(i32));
            if !default.is_empty() {
                it = it.default_values(default.iter().map(|i| i.to_string()));
            }
            it
        }
        Arg::UIntList {
            required,
            default,
            short,
            description,
            ..
        } => {
            let mut it = ClapArg::new(id)
                .long(long.clone())
                .value_name(long)
                .short(short_char(short))
                .help(help_text(description))
                .action(ArgAction::Append)
                .required(*required)
                .value_parser(value_parser!(u32));
            if !default.is_empty() {
                it = it.default_values(default.iter().map(|u| u.to_string()));
            }
            it
        }
        Arg::Custom { .. } => unreachable!("Custom args are not CLI-exposed"),
    }
}

// Apply a config.axl override to the just-built ClapArg: sets the default and
// drops `required` (the user has supplied the value, just not on the CLI).
fn with_override(mut clap_arg: ClapArg, arg: &Arg, override_strings: &[String]) -> ClapArg {
    clap_arg = match arg {
        Arg::StringList { .. }
        | Arg::BooleanList { .. }
        | Arg::IntList { .. }
        | Arg::UIntList { .. }
        | Arg::TrailingVarArgs { .. } => clap_arg.default_values(override_strings.iter().cloned()),
        _ => {
            if let Some(v) = override_strings.first() {
                clap_arg.default_value(v.clone())
            } else {
                clap_arg
            }
        }
    };
    clap_arg.required(false)
}

// ── Match → Arguments merge ────────────────────────────────────────────────

fn merge_args<'v>(
    schema: &SmallMap<String, Arg>,
    overrides_value: Value<'v>,
    matches: &ArgMatches,
    heap: Heap<'v>,
    scope: Scope<'_>,
) -> Arguments<'v> {
    let args = Arguments::new();
    for (name, arg) in schema.iter() {
        match arg {
            Arg::Custom { default, .. } => {
                let v = default
                    .map(|fv| fv.to_value())
                    .unwrap_or_else(|| heap.alloc(NoneType));
                args.insert(name.clone(), v);
            }
            cli => {
                let key = clap_id(scope, name, cli);
                // A feature arg loses its Clap registration on task commands
                // whose own args claim its long flag (see `task_command`); fall
                // back to the schema default there.
                if matches.try_contains_id(&key).is_err() {
                    if let Some(val) = schema_default_value(cli, heap) {
                        args.insert(name.clone(), val);
                    }
                    continue;
                }
                if let Some(val) = clap_to_value(cli, &key, matches, heap) {
                    args.insert(name.clone(), val);
                }
                // Track CLI-explicit keys so `ctx.args.is_explicit(name)`
                // can tell defaults from user-typed values downstream.
                if matches.value_source(&key) == Some(ValueSource::CommandLine) {
                    args.mark_explicit(name.clone());
                }
            }
        }
    }

    // Layer config.axl overrides for keys the user did NOT pass on the CLI.
    let Some(overrides) = overrides_value.downcast_ref::<Arguments>() else {
        return args;
    };
    for (k, v) in overrides.entries() {
        let user_explicit = schema
            .get(&k)
            .filter(|a| a.is_cli_exposed())
            .map(|a| {
                let key = clap_id(scope, &k, a);
                matches.try_contains_id(&key).is_ok()
                    && matches.value_source(&key) == Some(ValueSource::CommandLine)
            })
            .unwrap_or(false);
        if !user_explicit {
            args.insert(k, v);
        }
    }
    args
}

/// The value an arg resolves to when it has no Clap registration at all —
/// the schema default, mirroring what [`clap_to_value`] yields for an
/// untouched flag. `None` for `Custom` (handled by the caller).
fn schema_default_value<'v>(arg: &Arg, heap: Heap<'v>) -> Option<Value<'v>> {
    Some(match arg {
        Arg::Custom { .. } => return None,
        Arg::String { default, .. } => heap.alloc_str(default).to_value(),
        Arg::Boolean { default, .. } => heap.alloc(*default),
        Arg::Int { default, .. } => heap.alloc(*default).to_value(),
        Arg::UInt { default, .. } => heap.alloc(*default).to_value(),
        Arg::Positional { default, .. } => {
            heap.alloc(AllocList(default.clone().unwrap_or_default()))
        }
        Arg::TrailingVarArgs { .. } => heap.alloc(AllocList(Vec::<String>::new())),
        Arg::StringList { default, .. } => heap.alloc(AllocList(default.clone())),
        Arg::BooleanList { default, .. } => heap.alloc(AllocList(default.clone())),
        Arg::IntList { default, .. } => heap.alloc(AllocList(default.clone())),
        Arg::UIntList { default, .. } => heap.alloc(AllocList(default.clone())),
    })
}

fn clap_to_value<'v>(
    arg: &Arg,
    key: &str,
    matches: &ArgMatches,
    heap: Heap<'v>,
) -> Option<Value<'v>> {
    let v = match arg {
        Arg::Custom { .. } => return None,
        Arg::String { .. } => heap
            .alloc_str(matches.get_one::<String>(key).unwrap_or(&String::new()))
            .to_value(),
        Arg::Int { .. } => heap
            .alloc(*matches.get_one::<i32>(key).unwrap_or(&0))
            .to_value(),
        Arg::UInt { .. } => heap
            .alloc(*matches.get_one::<u32>(key).unwrap_or(&0))
            .to_value(),
        Arg::Boolean { .. } => heap.alloc(*matches.get_one::<bool>(key).unwrap_or(&false)),
        Arg::Positional { .. } | Arg::TrailingVarArgs { .. } => heap.alloc(AllocList(
            matches
                .get_many::<String>(key)
                .map_or(vec![], |it| it.map(|s| s.as_str()).collect()),
        )),
        Arg::StringList { .. } => heap.alloc(AllocList(
            matches
                .get_many::<String>(key)
                .unwrap_or_default()
                .map(|s| s.as_str())
                .collect::<Vec<_>>(),
        )),
        Arg::BooleanList { .. } => heap.alloc(AllocList(
            matches
                .get_many::<bool>(key)
                .unwrap_or_default()
                .copied()
                .collect::<Vec<_>>(),
        )),
        Arg::IntList { .. } => heap.alloc(AllocList(
            matches
                .get_many::<i32>(key)
                .unwrap_or_default()
                .copied()
                .collect::<Vec<_>>(),
        )),
        Arg::UIntList { .. } => heap.alloc(AllocList(
            matches
                .get_many::<u32>(key)
                .unwrap_or_default()
                .copied()
                .collect::<Vec<_>>(),
        )),
    };
    Some(v)
}

// ── Override stringification (for Clap default_value) ──────────────────────

fn stringify_overrides(
    overrides_value: Value<'_>,
) -> std::collections::HashMap<String, Vec<String>> {
    let Some(args) = overrides_value.downcast_ref::<Arguments>() else {
        return std::collections::HashMap::new();
    };
    args.entries()
        .into_iter()
        .map(|(k, v)| {
            let elements = if let Some(list) = ListRef::from_value(v) {
                list.iter().map(stringify_value).collect()
            } else {
                vec![stringify_value(v)]
            };
            (k, elements)
        })
        .collect()
}

fn stringify_value(v: Value<'_>) -> String {
    if let Some(s) = v.unpack_str() {
        return s.to_owned();
    }
    let s = v.to_string();
    if v.get_type() == "bool" {
        s.to_lowercase()
    } else {
        s
    }
}

// ── Per-feature help block ─────────────────────────────────────────────────
//
// Built once per feature. Each task command registers these args hidden (so
// they parse but don't clutter `--help`); `aspect feature [<name>]` renders
// them for discovery via `Cmd::print_feature_help`.

struct FeatureBlock {
    args: Vec<(String, Arg)>,
    heading: String,
    prefix: String,
}

fn feature_block(feat: &dyn FeatureLike<'_>) -> Option<FeatureBlock> {
    let mut args: Vec<(String, Arg)> = feat
        .args()
        .iter()
        .filter(|(_, v)| v.is_cli_exposed())
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect();
    if args.is_empty() {
        return None;
    }

    // Bake config.axl overrides into the schema defaults so `--help` shows them.
    for (k, vals) in stringify_overrides(feat.overrides()) {
        let Some((_, arg)) = args.iter_mut().find(|(name, _)| name == &k) else {
            continue;
        };
        let Some(first) = vals.first() else { continue };
        match arg {
            Arg::Boolean { default, .. } => *default = first == "true",
            Arg::String { default, .. } => *default = first.clone(),
            Arg::Int { default, .. } => {
                if let Ok(v) = first.parse() {
                    *default = v;
                }
            }
            Arg::UInt { default, .. } => {
                if let Ok(v) = first.parse() {
                    *default = v;
                }
            }
            _ => {}
        }
    }

    let heading = format!("{} Options", feat.display_name());
    Some(FeatureBlock {
        args,
        heading,
        prefix: feat.name(),
    })
}

// ── `aspect describe` rendering ────────────────────────────────────────────

/// One CLI argument, described by the flag string a caller would actually type.
///
/// `scope` decides that string: task args are bare kebab (`--scope`), feature
/// args carry their feature prefix (`--tips:silence`). Both go through
/// [`long_flag`], the same helper that builds the real Clap arg, so what is
/// described and what parses cannot drift.
fn describe_arg(scope: Scope<'_>, name: &str, arg: &Arg) -> serde_json::Value {
    use serde_json::json;

    let flag = match arg {
        Arg::Positional { .. } | Arg::TrailingVarArgs { .. } => None,
        _ => Some(format!("--{}", long_flag(scope, name, arg))),
    };
    let (kind, default, values, description, short) = match arg {
        Arg::String {
            default,
            values,
            description,
            short,
            ..
        } => ("string", json!(default), json!(values), description, short),
        Arg::Boolean {
            default,
            description,
            short,
            ..
        } => ("boolean", json!(default), json!(null), description, short),
        Arg::Int {
            default,
            description,
            short,
            ..
        } => ("int", json!(default), json!(null), description, short),
        Arg::UInt {
            default,
            description,
            short,
            ..
        } => ("uint", json!(default), json!(null), description, short),
        Arg::StringList {
            default,
            description,
            short,
            ..
        } => (
            "string_list",
            json!(default),
            json!(null),
            description,
            short,
        ),
        Arg::BooleanList {
            default,
            description,
            short,
            ..
        } => (
            "boolean_list",
            json!(default),
            json!(null),
            description,
            short,
        ),
        Arg::IntList {
            default,
            description,
            short,
            ..
        } => ("int_list", json!(default), json!(null), description, short),
        Arg::UIntList {
            default,
            description,
            short,
            ..
        } => ("uint_list", json!(default), json!(null), description, short),
        Arg::Positional {
            default,
            description,
            ..
        } => (
            "positional",
            json!(default),
            json!(null),
            description,
            &None,
        ),
        Arg::TrailingVarArgs { description } => (
            "trailing_var_args",
            json!(null),
            json!(null),
            description,
            &None,
        ),
        // Filtered out by `is_cli_exposed` before reaching here.
        Arg::Custom { description, .. } => ("custom", json!(null), json!(null), description, &None),
    };
    // `Arg::is_required` reports false for positionals — they carry cardinality
    // instead of a `required` flag — so a `minimum = 1` positional would read as
    // optional. Derive requiredness from the cardinality and report the bounds,
    // or a caller cannot tell `aspect run` (exactly one target) from a task that
    // takes none.
    let (required, minimum, maximum) = match arg {
        Arg::Positional {
            minimum, maximum, ..
        } => (*minimum >= 1, json!(minimum), json!(maximum)),
        _ => (arg.is_required(), json!(null), json!(null)),
    };
    json!({
        "name": name,
        "type": kind,
        "flag": flag,
        "short": short.as_ref().map(|s| format!("-{s}")),
        "required": required,
        "minimum": minimum,
        "maximum": maximum,
        "default": default,
        "allowed_values": values,
        "description": description,
    })
}

/// Re-type a `config.axl` override for the JSON `default` field.
///
/// [`stringify_overrides`] flattens every override to `Vec<String>` for Clap's
/// benefit. Handing that back verbatim would describe an int default as
/// `["2"]`, so scalars collapse to a single value parsed back to the arg's own
/// type and only genuine list args stay arrays.
fn override_as_default(arg: &Arg, over: &[String]) -> serde_json::Value {
    use serde_json::json;

    match arg {
        // Positional values are genuinely strings (target patterns), so they
        // stay as they came.
        Arg::StringList { .. } | Arg::Positional { .. } => json!(over),
        Arg::BooleanList { .. } => json!(over.iter().map(|v| v == "true").collect::<Vec<_>>()),
        Arg::IntList { .. } | Arg::UIntList { .. } => json!(
            over.iter()
                .map(|v| v
                    .parse::<i64>()
                    .map(|n| json!(n))
                    .unwrap_or_else(|_| json!(v)))
                .collect::<Vec<_>>()
        ),
        _ => match over.first() {
            None => json!(null),
            Some(first) => match arg {
                Arg::Boolean { .. } => json!(first == "true"),
                Arg::Int { .. } | Arg::UInt { .. } => first
                    .parse::<i64>()
                    .map(|n| json!(n))
                    .unwrap_or_else(|_| json!(first)),
                _ => json!(first),
            },
        },
    }
}

/// Every runnable command with its summary, and nothing else.
fn describe_index(
    version: &str,
    tasks: &[&dyn TaskLike<'_>],
    features: &[&dyn FeatureLike<'_>],
) -> serde_json::Value {
    use serde_json::json;

    let mut commands: Vec<serde_json::Value> = tasks
        .iter()
        .map(|task| {
            let mut path = task.group().clone();
            path.push(task.kind());
            json!({
                "command": format!("aspect {}", path.join(" ")),
                "summary": task.summary(),
            })
        })
        .collect();
    commands.sort_by(|a, b| a["command"].as_str().cmp(&b["command"].as_str()));

    json!({
        "aspect_cli_version": version,
        "commands": commands,
        "features": features.iter().map(|f| f.name()).collect::<Vec<_>>(),
        "next": {
            "task_detail": "aspect describe '<command without the leading `aspect `>' — e.g. aspect describe 'cache diff'",
            "feature_flags": "aspect feature <name>",
        },
    })
}

/// Pull one task out of a full [`describe_json`] document by its command path,
/// with or without the leading `aspect `.
fn select_task(full: &serde_json::Value, name: &str) -> Option<serde_json::Value> {
    let want = name.trim().trim_start_matches("aspect ").trim();
    full["tasks"].as_array()?.iter().find_map(|t| {
        let cmd = t["command"].as_str()?;
        (cmd.trim_start_matches("aspect ") == want).then(|| t.clone())
    })
}

/// The full resolved surface as JSON: every task reachable in this repo, the
/// flags each accepts, and the feature flags accepted everywhere.
///
/// This exists because the Aspect surface is per-repo — a caller cannot know
/// what `aspect <task>` means here without asking. One call answers it.
fn describe_json(
    version: &str,
    tasks: &[&dyn TaskLike<'_>],
    features: &[&dyn FeatureLike<'_>],
    aspect_root: &Path,
    modules: &[Mod],
) -> serde_json::Value {
    use serde_json::json;

    let described_tasks: Vec<serde_json::Value> = tasks
        .iter()
        .map(|task| {
            let kind = task.kind();
            let mut path = task.group().clone();
            path.push(kind.clone());
            let overrides = stringify_overrides(task.overrides());
            let args: Vec<serde_json::Value> = task
                .cli_args()
                .into_iter()
                .map(|(arg_name, arg)| {
                    let mut described = describe_arg(Scope::Task, arg_name, arg);
                    // A config.axl override is what the caller will actually
                    // get, so report it as the default and say where it came
                    // from rather than showing the unreachable schema value.
                    if let Some(over) = overrides.get(arg_name)
                        && let Some(obj) = described.as_object_mut()
                    {
                        obj.insert("default".into(), override_as_default(arg, over));
                        obj.insert("default_from_config".into(), json!(true));
                    }
                    described
                })
                .collect();
            json!({
                "command": format!("aspect {}", path.join(" ")),
                "path": path,
                "name": kind,
                "summary": task.summary(),
                "description": task.description(),
                "defined_in": defined_in_label(task.path(), aspect_root, modules),
                "args": args,
            })
        })
        .collect();

    let described_features: Vec<serde_json::Value> = features
        .iter()
        .filter_map(|feat| {
            let block = feature_block(*feat)?;
            // `feature_block` bakes scalar overrides into its schema but skips
            // list-valued ones, so re-apply them here for the same reason task
            // args do it: a caller must see the default execution will use, not
            // one it can never observe.
            let overrides = stringify_overrides(feat.overrides());
            let flags: Vec<serde_json::Value> = block
                .args
                .iter()
                .map(|(arg_name, arg)| {
                    let mut described = describe_arg(Scope::Feature(&block.prefix), arg_name, arg);
                    if let Some(over) = overrides.get(arg_name)
                        && let Some(obj) = described.as_object_mut()
                    {
                        obj.insert("default".into(), override_as_default(arg, over));
                        obj.insert("default_from_config".into(), json!(true));
                    }
                    described
                })
                .collect();
            Some(json!({
                "name": feat.name(),
                "summary": feat.summary(),
                "description": feat.description(),
                "defined_in": defined_in_label(feat.path(), aspect_root, modules),
                "flags": flags,
            }))
        })
        .collect();

    json!({
        "aspect_cli_version": version,
        "tasks": described_tasks,
        "features": described_features,
    })
}

// ── `aspect feature` rendering ─────────────────────────────────────────────

/// Render the `aspect feature` listing: one row per feature, keyed by the
/// kebab slug the user passes to `aspect feature <name>`, with its summary.
fn render_feature_list(
    version: &str,
    blocks: &[(&dyn FeatureLike<'_>, FeatureBlock)],
    color: bool,
) -> String {
    let width = blocks
        .iter()
        .map(|(f, _)| f.name().len())
        .max()
        .unwrap_or(0);
    let (bold, bold_underline, reset) = if color {
        ("\x1b[1m", "\x1b[1;4m", "\x1b[0m")
    } else {
        ("", "", "")
    };
    let mut out = format!(
        "{}\n\n{bold_underline}Features:{reset}\n",
        banner::line_colored(version, color)
    );
    for (feat, _) in blocks {
        let slug = feat.name();
        let pad = " ".repeat(width - slug.len() + 2);
        out.push_str(&format!(
            "  {bold}{}{reset}{}{}\n",
            slug,
            pad,
            feat.summary()
        ));
    }
    out.push_str("\nRun `aspect feature <NAME>` to see a feature's flags.\n");
    out
}

/// Build the `aspect feature <name>` help command: the feature's prose (or its
/// "defined in" line when it has none) above its flags, rendered with the same
/// clap formatting the flags used to get inline in each task's `--help`.
fn render_feature_detail(
    version: &str,
    feat: &dyn FeatureLike<'_>,
    block: &FeatureBlock,
    aspect_root: &Path,
    modules: &[Mod],
) -> Command {
    let context = format!(
        "\x1b[3m{}\x1b[0m feature defined in \x1b[3m{}\x1b[0m",
        feat.export_name().unwrap_or_default(),
        defined_in_label(feat.path(), aspect_root, modules),
    );
    let body = if !feat.description().is_empty() {
        feat.description()
    } else {
        feat.summary()
    };
    let about = if body.is_empty() {
        context
    } else {
        format!("{body}\n\n{context}")
    };
    let mut cmd = Command::new(format!("feature {}", feat.name()))
        .no_binary_name(true)
        .disable_help_flag(true)
        .help_template(format!(
            "{}\n\n{about}\n\n{{all-args}}",
            banner::line(version)
        ));
    for (arg_name, arg) in block.args.iter() {
        cmd = cmd.arg(
            arg_to_clap(Scope::Feature(&block.prefix), arg_name, arg)
                .help_heading(block.heading.clone()),
        );
    }
    cmd
}

// ── Per-task subcommand assembly ───────────────────────────────────────────

fn task_command(
    index: usize,
    task: &dyn TaskLike<'_>,
    label: &str,
    feature_blocks: &[FeatureBlock],
    cli_header: &str,
) -> Command {
    let kind = task.kind();
    let friendly_kind = task.friendly_kind();
    let display = if !friendly_kind.is_empty() {
        friendly_kind
    } else {
        to_display_name(&kind)
    };

    let context_line = format!(
        "\x1b[3m{}\x1b[0m task defined in \x1b[3m{}\x1b[0m",
        kind, label,
    );
    let about = if task.summary().is_empty() {
        if needs_summary_warning(task.summary(), label) {
            warn_missing_summary(&kind, label);
        }
        context_line.clone()
    } else {
        task.summary().clone()
    };
    let help_header = if task.summary().is_empty() && task.description().is_empty() {
        None
    } else {
        let body = if !task.description().is_empty() {
            task.description().clone()
        } else {
            task.summary().clone()
        };
        Some(format!("{}\n\n{}", body, context_line))
    };

    let mut cmd = Command::new(kind)
        .about(about)
        .display_order(TASK_COMMAND_DISPLAY_ORDER)
        .arg(
            ClapArg::new(TASK_ID_KEY)
                .long(TASK_ID_KEY)
                .hide(true)
                .hide_default_value(true)
                .hide_short_help(true)
                .hide_possible_values(true)
                .hide_long_help(true)
                .value_parser(value_parser!(usize))
                .default_value(index.to_string()),
        );

    let overrides = stringify_overrides(task.overrides());
    let heading = format!("{} Options", display);
    for (arg_name, arg) in task.cli_args() {
        let mut clap_arg = arg_to_clap(Scope::Task, arg_name, arg).help_heading(heading.clone());
        if let Some(over) = overrides.get(arg_name) {
            clap_arg = with_override(clap_arg, arg, over);
        }
        cmd = cmd.arg(clap_arg);
    }

    // Feature flags stay parseable on the task command but are hidden from
    // `--help`; `aspect feature [<name>]` surfaces them instead (see the footer
    // appended to the help template below).
    //
    // A task's own args win any collision: a feature arg whose long flag matches
    // a task arg's name or long (e.g. a `long`-overridden `--deployment` vs the
    // auth tasks' `deployment`) is not registered here — `merge_args` then falls
    // back to the feature arg's schema default, leaving the feature inert on
    // that task rather than panicking on a duplicate Clap arg.
    let claimed: HashSet<String> = task
        .cli_args()
        .into_iter()
        .flat_map(|(arg_name, arg)| [arg_name.to_owned(), long_flag(Scope::Task, arg_name, arg)])
        .collect();
    for block in feature_blocks {
        for (arg_name, arg) in block.args.iter() {
            if claimed.contains(&long_flag(Scope::Feature(&block.prefix), arg_name, arg)) {
                continue;
            }
            let clap_arg = arg_to_clap(Scope::Feature(&block.prefix), arg_name, arg).hide(true);
            cmd = cmd.arg(clap_arg);
        }
    }

    // Always use a custom template so the grey "Aspect CLI v… — docs URL"
    // header lands at the top. When the task supplies its own help_header
    // body (summary/description), use that as the about block; otherwise
    // fall back to clap's `{about-with-newline}`.
    let about_block = match help_header {
        Some(h) => format!("{h}\n"),
        None => "{about-with-newline}".to_string(),
    };
    let feature_footer = "\x1b[2mFeatures add CI reporting and artifact integrations \
         (GitHub, Buildkite, GitLab, CircleCI, telemetry). Their flags are accepted here \
         but hidden; run `aspect feature` to list them.\x1b[0m";
    cmd = cmd.help_template(format!(
        "{cli_header}\n\n{about_block}\n{{usage-heading}} {{usage}}\n\n{{all-args}}\n\n{feature_footer}"
    ));
    cmd
}

// ── Subgroup tree ──────────────────────────────────────────────────────────

#[derive(Default)]
struct Tree {
    subgroups: BTreeMap<String, Tree>,
    tasks: BTreeMap<String, Command>,
}

impl Tree {
    fn insert(
        &mut self,
        task: &dyn TaskLike<'_>,
        label: &str,
        cmd: Command,
    ) -> Result<(), CmdError> {
        let group = task.group().clone();
        if group.len() > MAX_TASK_GROUPS {
            return Err(CmdError::TooManyGroups(
                task.kind(),
                label.to_owned(),
                MAX_TASK_GROUPS,
            ));
        }
        // `main` routes these top-level commands before task parsing, so a
        // top-level task of the same kind would never run. Reject it rather than
        // let it silently disappear; nested under a group it is reachable.
        if group.is_empty() && RESERVED_TOP_LEVEL_COMMANDS.contains(&task.kind().as_str()) {
            return Err(CmdError::ReservedName(
                task.kind(),
                label.to_owned(),
                task.kind(),
            ));
        }
        self.insert_at(&task.kind(), &group[..], &group[..], label, cmd)
    }

    fn insert_at(
        &mut self,
        name: &str,
        full_group: &[String],
        remaining: &[String],
        label: &str,
        cmd: Command,
    ) -> Result<(), CmdError> {
        if remaining.is_empty() {
            if self.subgroups.contains_key(name) || self.tasks.contains_key(name) {
                return Err(CmdError::NameConflict(
                    name.to_owned(),
                    full_group.to_vec(),
                    label.to_owned(),
                ));
            }
            self.tasks.insert(name.to_owned(), cmd);
            return Ok(());
        }
        let head = &remaining[0];
        if self.tasks.contains_key(head) {
            return Err(CmdError::NameConflict(
                head.clone(),
                full_group.to_vec(),
                label.to_owned(),
            ));
        }
        let sub = self.subgroups.entry(head.clone()).or_default();
        sub.insert_at(name, full_group, &remaining[1..], label, cmd)
    }

    /// What each subgroup contains, as a comma-joined list of its task kinds
    /// and nested group names. A group has no summary of its own to show, and
    /// "auth task group" tells a reader nothing about whether the command they
    /// want is inside — listing the members does.
    fn group_rows(&self) -> Vec<(String, String)> {
        self.subgroups
            .iter()
            .map(|(name, sub)| (name.clone(), sub.member_list()))
            .collect()
    }

    fn member_list(&self) -> String {
        let mut members: Vec<String> = self.tasks.keys().cloned().collect();
        members.extend(self.subgroups.keys().map(|g| format!("{g}/")));
        elide(&members, MEMBER_LIST_WIDTH)
    }

    fn attach(self, mut root: Command, version: &str) -> Result<Command, CmdError> {
        // Subgroups (rendered hidden, with their own help template).
        let header = banner::line(version);
        for (name, sub) in self.subgroups {
            let sub_rows = sub.group_rows();
            let about = format!("\x1b[3m{}\x1b[0m: {}", name, sub.member_list());
            let mut template =
                format!("{header}\n\n{{about-with-newline}}\n{{usage-heading}} {{usage}}");
            if !sub.tasks.is_empty() {
                template.push_str("\n\n\x1b[1;4mTasks:\x1b[0m\n{subcommands}");
            }
            template.push_str(&group_section(&sub_rows));
            let template = format!(
                "{}\n\n\x1b[1;4mOptions:\x1b[0m\n{{options}}",
                template.trim_end()
            );
            let mut subcmd = Command::new(name.clone())
                .subcommand_value_name("TASK|GROUP")
                .about(about)
                .display_order(TASK_GROUP_DISPLAY_ORDER)
                .hide(true)
                .help_template(template);
            subcmd = sub.attach(subcmd, version)?;
            if root.find_subcommand(&name).is_some() {
                return Err(CmdError::NameConflict(name, vec![], String::new()));
            }
            root = root.subcommand(subcmd);
        }
        // Leaf task subcommands.
        for (name, subcmd) in self.tasks {
            if root.find_subcommand(&name).is_some() {
                return Err(CmdError::NameConflict(name, vec![], String::new()));
            }
            root = root.subcommand(subcmd);
        }
        if root.get_subcommands().next().is_some() {
            root = root.arg_required_else_help(true);
        }
        Ok(root)
    }
}

/// Width budget for a group's member list before it is elided.
const MEMBER_LIST_WIDTH: usize = 58;

/// Join `items`, trimming to `width` and appending `…` plus the count dropped.
fn elide(items: &[String], width: usize) -> String {
    let mut out = String::new();
    for (i, item) in items.iter().enumerate() {
        let sep = if i == 0 { "" } else { ", " };
        if !out.is_empty() && out.len() + sep.len() + item.len() > width {
            return format!("{out}, … (+{} more)", items.len() - i);
        }
        out.push_str(sep);
        out.push_str(item);
    }
    out
}

fn group_section(rows: &[(String, String)]) -> String {
    if rows.is_empty() {
        return String::new();
    }
    let max_len = rows.iter().map(|(n, _)| n.len()).max().unwrap_or(0);
    let mut s = String::from("\n\n\x1b[1;4mTask Groups:\x1b[0m\n");
    for (name, members) in rows {
        let pad = " ".repeat(max_len - name.len() + 2);
        s.push_str(&format!("  \x1b[1m{}\x1b[0m{}{}\n", name, pad, members));
    }
    s
}

