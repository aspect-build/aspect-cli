//! Printing a version's module. Resolution has already decided everything;
//! this turns the IR into tokens and the tokens into formatted source.

mod handle;
mod implement;
mod member;
mod options;
mod starlark;
pub mod types;

use crate::ir::{Class, Implementation};
use anyhow::{Result, bail};
use proc_macro2::TokenStream;
use quote::quote;

/// The source of the module for one Bazel version.
pub fn module(
    label: &str,
    classes: &[Class],
    impls: &[Implementation],
    schema: Option<&crate::options::Schema>,
) -> Result<String> {
    let bound = types::bound_map(
        classes
            .iter()
            .map(|c| (c.internal.as_str(), c.rust.as_str(), c.type_params.len())),
    );
    let mut problems = Vec::new();
    let handles: Vec<TokenStream> = classes
        .iter()
        .map(|c| handle::class(c, &bound, label, &mut problems))
        .collect();
    let facets = starlark::facets(label, classes, &bound, &mut problems)?;
    let implemented = implement::implementations(impls, &bound, label, &mut problems);
    if !problems.is_empty() {
        problems.sort();
        problems.dedup();
        bail!("{}", problems.join("\n"));
    }
    let options = schema.map(options::module).unwrap_or_default();
    let reexports = crate::jdk::reexports();
    let intro = [
        format!(" Generated by blazon from Bazel {label} (`A-server.jar`). Do not edit."),
        String::new(),
        " A handle owns one local reference, released when it drops, so it is valid only on the"
            .to_string(),
        " thread that made it. Standard Java types are `blazon_rt::java`, re-exported here."
            .to_string(),
    ];
    let tokens = quote!(
        #(#![doc = #intro])*
        #![allow(
            non_snake_case,
            clippy::too_many_arguments,
            clippy::type_complexity,
            clippy::new_ret_no_self,
            clippy::needless_lifetimes
        )]

        use jni::JNIEnv;
        use jni::objects::JValue;

        #reexports

        /// The Bazel release these bindings were generated from.
        pub const BAZEL_VERSION: &str = #label;

        #(#handles)*
        #facets
        #implemented
        #options
    );
    format(tokens)
}

/// Formats tokens as the source of a file.
pub fn format(tokens: TokenStream) -> Result<String> {
    let file: syn::File = syn::parse2(tokens)?;
    Ok(prettyplease::unparse(&file))
}

/// The file that names every version's module and dispatches on the version.
pub fn mod_rs(
    out: &std::path::Path,
    mods: &[String],
    starlark: bool,
    options: bool,
) -> Result<String> {
    let mut mods = mods.to_vec();
    mods.sort();
    let decls = mods.iter().map(|m| {
        let path = out.join(format!("{m}.rs")).display().to_string();
        let name = syn::Ident::new(m, proc_macro2::Span::call_site());
        quote!(#[path = #path] pub mod #name;)
    });
    let labels: Vec<String> = mods
        .iter()
        .map(|m| m.trim_start_matches('v').replace('_', "."))
        .collect();
    let register = if starlark {
        let arms = mods.iter().zip(&labels).map(|(m, l)| {
            let name = syn::Ident::new(m, proc_macro2::Span::call_site());
            quote!(#l => #name::register(),)
        });
        quote!(
            /// Registers the generated Starlark types of the Bazel `version` being hosted.
            pub fn register(version: &str) -> Result<(), String> {
                match version {
                    #(#arms)*
                    other => return Err(format!("no Starlark types were generated for Bazel {other}")),
                }
                Ok(())
            }
        )
    } else {
        quote!()
    };
    let schemas = if options {
        let arms = mods.iter().zip(&labels).map(|(m, l)| {
            let name = syn::Ident::new(m, proc_macro2::Span::call_site());
            quote!(#l => Some(#name::options::OPTIONS),)
        });
        quote!(
            /// The option schema of the Bazel `version`, when the spec has `[options]`.
            pub fn options(version: &str) -> Option<&'static [blazon_rt::options::OptionDef]> {
                match version {
                    #(#arms)*
                    _ => None,
                }
            }
        )
    } else {
        quote!()
    };
    let tokens = quote!(
        #(#decls)*

        /// The Bazel versions with bindings.
        pub const SUPPORTED: &[&str] = &[#(#labels),*];

        #register

        #schemas
    );
    format(tokens)
}
